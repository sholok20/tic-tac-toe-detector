"""**RMSE Calculation Function**

This function calculates the Root Mean Squared Error (RMSE) between:
- The true number of symbols
- The predicted number of symbols


"""

def compute_rmse(true_counts, pred_counts):

    true_counts = np.array(true_counts)
    pred_counts = np.array(pred_counts)

    return np.sqrt(np.mean((true_counts - pred_counts) ** 2))

print("RMSE function ready")

